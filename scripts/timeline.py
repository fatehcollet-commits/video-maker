#!/usr/bin/env python3
"""
Timeline generator: reads out/ep01_rule_four/lines.json and emits
src/stories/ep01_rule_four/timeline.ts with chunked caption cards
(MAX_WORDS=4, MAX_CHARS=26, non-overlapping, max 1 yellow #ffd84a word per card,
and isFinal=true on L26 held cleanly into the 1.5s suspense tail).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent

MAX_WORDS = 4
MAX_CHARS = 26

HORROR_WORDS = [
    "midnight", "bloodstained", "unhinged", "clicked", "cracked", "sideways",
    "dropped", "twelve", "white", "eyes", "strobe", "flashed", "cut", "inside",
    "whispered", "behind", "thermal", "celsius", "panting", "mouth", "scratches",
    "wired", "glass", "sensor", "blinked", "red", "four", "never", "name",
    "clearance", "unlock", "wait", "no", "fog", "breath", "stopped", "limits",
    "open", "door", "two", "away",
]


def normalize_word(w: str) -> str:
    return re.sub(r"[^a-z0-9]", "", w.lower())


def pick_highlight_word(words: list[str]) -> int:
    """Return index of at most ONE hot yellow word from HORROR_WORDS, or -1."""
    best_idx = -1
    best_rank = 10_000
    for idx, w in enumerate(words):
        norm = normalize_word(w)
        if norm in HORROR_WORDS:
            rank = HORROR_WORDS.index(norm)
            if rank < best_rank:
                best_rank = rank
                best_idx = idx
    return best_idx


def chunk_line_words(words_meta: list[dict[str, Any]]) -> list[list[dict[str, Any]]]:
    chunks: list[list[dict[str, Any]]] = []
    current: list[dict[str, Any]] = []
    for w in words_meta:
        candidate = current + [w]
        text_len = len(" ".join(x["word"] for x in candidate))
        if current and (len(candidate) > MAX_WORDS or text_len > MAX_CHARS):
            chunks.append(current)
            current = [w]
        else:
            current = candidate
    if current:
        chunks.append(current)
    return chunks


def main() -> None:
    lines_json_path = ROOT / "out" / "ep01_rule_four" / "lines.json"
    if not lines_json_path.exists():
        raise FileNotFoundError(f"Missing {lines_json_path}; run scripts/voice_el.py first.")

    data = json.loads(lines_json_path.read_text(encoding="utf-8"))
    lines = data["lines"]
    voice_dur = float(data["voice_dur"])
    tail_dur = float(data["tail_dur"])
    total_dur = float(data["total_dur"])

    cards: list[dict[str, Any]] = []
    line_windows: dict[str, dict[str, Any]] = {}

    for i, line in enumerate(lines):
        lid = line["id"]
        line_start = float(line["start"])
        line_end = float(line["end"])
        next_start = float(lines[i + 1]["start"]) if i + 1 < len(lines) else total_dur

        line_windows[lid] = {
            "id": lid,
            "text": line["text"],
            "start": round(line_start, 4),
            "end": round(line_end, 4),
        }

        chunks = chunk_line_words(line["words"])
        is_final_line = lid == "L26"
        for c_idx, chunk in enumerate(chunks):
            c_start = float(chunk[0]["start"])
            c_end = float(chunk[-1]["end"])
            # Extend final card of L26 cleanly into the 1.5s suspense tail
            if is_final_line and c_idx == len(chunks) - 1:
                c_end = max(c_end, total_dur - 0.12)
            elif c_idx + 1 < len(chunks):
                next_c_start = float(chunks[c_idx + 1][0]["start"])
                c_end = min(next_c_start - 0.015, max(c_end + 0.04, c_start + 0.12))
            else:
                c_end = min(next_start - 0.02, c_end + 0.08)

            c_end = max(c_start + 0.10, c_end)
            word_strings = [w["word"] for w in chunk]
            hl_idx = pick_highlight_word(word_strings)
            cards.append({
                "id": f"{lid}_C{c_idx + 1}",
                "lineId": lid,
                "words": word_strings,
                "text": " ".join(word_strings),
                "highlightIndex": hl_idx,
                "start": round(c_start, 4),
                "end": round(c_end, 4),
                "isFinal": is_final_line,
            })

    # Enforce strict non-overlap invariant across all cards
    for idx in range(len(cards) - 1):
        if cards[idx]["end"] > cards[idx + 1]["start"] - 0.005:
            cards[idx]["end"] = round(max(cards[idx]["start"] + 0.05, cards[idx + 1]["start"] - 0.005), 4)
        assert cards[idx]["end"] <= cards[idx + 1]["start"], f"Card overlap at {cards[idx]['id']}"

    ts_out = ROOT / "src" / "stories" / "ep01_rule_four" / "timeline.ts"
    ts_out.parent.mkdir(parents=True, exist_ok=True)
    ts_content = (
        "// AUTO-GENERATED BY scripts/timeline.py — DO NOT EDIT BY HAND\n"
        "import type { LineId } from './lines';\n\n"
        "export interface CaptionCard {\n"
        "  id: string;\n"
        "  lineId: LineId;\n"
        "  words: string[];\n"
        "  text: string;\n"
        "  highlightIndex: number;\n"
        "  start: number;\n"
        "  end: number;\n"
        "  isFinal: boolean;\n"
        "}\n\n"
        "export interface LineWindow {\n"
        "  id: LineId;\n"
        "  text: string;\n"
        "  start: number;\n"
        "  end: number;\n"
        "}\n\n"
        f"export const VOICE_DURATION = {round(voice_dur, 4)};\n"
        f"export const TAIL_DURATION = {round(tail_dur, 4)};\n"
        f"export const TOTAL_DURATION = {round(total_dur, 4)};\n\n"
        f"export const LINE_WINDOWS: Record<LineId, LineWindow> = {json.dumps(line_windows, indent=2)} as Record<LineId, LineWindow>;\n\n"
        f"export const CAPTION_CARDS: CaptionCard[] = {json.dumps(cards, indent=2)} as CaptionCard[];\n"
    )
    ts_out.write_text(ts_content, encoding="utf-8")
    print(f"[timeline] Wrote {len(cards)} caption cards across {len(lines)} lines -> {ts_out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
